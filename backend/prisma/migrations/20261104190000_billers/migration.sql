CREATE TABLE IF NOT EXISTS public.billers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    biller_code VARCHAR(50),
    name VARCHAR(200) NOT NULL,
    company_name VARCHAR(200),
    email VARCHAR(255),
    phone VARCHAR(30),
    mobile VARCHAR(30),
    address TEXT,
    city VARCHAR(100),
    state VARCHAR(100),
    country VARCHAR(100),
    postal_code VARCHAR(20),
    vat_number VARCHAR(100),
    tax_number VARCHAR(100),
    commission_rate NUMERIC(8,2) DEFAULT 0,
    opening_balance NUMERIC(15,2) DEFAULT 0,
    current_balance NUMERIC(15,2) DEFAULT 0,
    notes TEXT,
    status VARCHAR(20) DEFAULT 'active',
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_billers_company_code UNIQUE (company_id, biller_code),
    CONSTRAINT chk_billers_status CHECK (status IN ('active', 'inactive', 'blocked')),
    CONSTRAINT chk_billers_commission CHECK (commission_rate >= 0 AND commission_rate <= 100)
);
CREATE INDEX IF NOT EXISTS idx_billers_company ON public.billers(company_id);
