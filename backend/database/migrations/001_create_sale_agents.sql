-- Sale Agents table aligned with the supplied s-a.csv columns.
-- Safe to run on an existing database; it does not drop or reset data.
CREATE TABLE IF NOT EXISTS public.sale_agents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES public.companies(id) ON DELETE CASCADE,
  agent_code VARCHAR(50),
  agent_name VARCHAR(200) NOT NULL,
  email VARCHAR(191),
  mobile VARCHAR(50),
  commission_type VARCHAR(20) NOT NULL DEFAULT 'percentage' CHECK (commission_type IN ('percentage','fixed')),
  commission_rate NUMERIC(14,2) NOT NULL DEFAULT 0,
  status VARCHAR(30) NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_sale_agents_company_id ON public.sale_agents(company_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_sale_agents_company_code ON public.sale_agents(company_id, agent_code) WHERE agent_code IS NOT NULL;
